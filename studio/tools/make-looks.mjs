// Copies episodes/<slug>-apple to episodes/<slug>-<look> for each look in studio/looks (or the ones named) and wires
// the look in: assets/look.css after apple.css, assets/look.js after apple.js, plus its fonts. Voice, timing and
// scenes are untouched. Rerun after changing the apple build: it replaces the copies (renders are kept).
//
// Usage (repo root):  node studio/tools/make-looks.mjs ep18-always-on-agents-60s [reel soft ...]
import { cpSync, existsSync, readFileSync, writeFileSync, readdirSync, rmSync, mkdirSync, renameSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const [slug, ...only] = process.argv.slice(2);
if (!slug) { console.error("usage: node studio/tools/make-looks.mjs <slug> [looks...]"); process.exit(1); }
const src = join(repo, "episodes", `${slug}-apple`);
if (!existsSync(src)) { console.error(`${src} not found`); process.exit(1); }
const looksDir = join(repo, "studio", "looks");
const looks = only.length ? only : readdirSync(looksDir).filter((d) => existsSync(join(looksDir, d, "look.css")));
const skip = new Set(["renders", "snapshots", ".hyperframes", "node_modules"]);

for (const look of looks) {
  const dst = join(repo, "episodes", `${slug}-${look}`);
  const keep = join(repo, "episodes", `.${slug}-${look}-renders`);
  if (existsSync(join(dst, "renders"))) renameSync(join(dst, "renders"), keep);
  rmSync(dst, { recursive: true, force: true });
  cpSync(src, dst, { recursive: true, filter: (p) => !skip.has(basename(p)) });
  if (existsSync(keep)) renameSync(keep, join(dst, "renders"));
  const L = join(looksDir, look);
  cpSync(join(L, "look.css"), join(dst, "assets", "look.css"));
  cpSync(join(L, "look.js"), join(dst, "assets", "look.js"));
  if (existsSync(join(L, "fonts"))) { mkdirSync(join(dst, "assets", "fonts"), { recursive: true }); for (const f of readdirSync(join(L, "fonts"))) cpSync(join(L, "fonts", f), join(dst, "assets", "fonts", f)); }
  const ip = join(dst, "index.html");
  let idx = readFileSync(ip, "utf8");
  idx = idx.replace(/(<link rel="stylesheet" href="assets\/apple.css">)/, `$1\n    <link rel="stylesheet" href="assets/look.css">`)
    .replace(/(<script src="assets\/apple.js"><\/script>)/, `$1\n    <script src="assets/look.js"></script>`)
    .replace(/<!-- APPLE variant[^]*?-->/, `<!-- ${look.toUpperCase()} variant: the ${slug}-apple scenes restyled by assets/look.css + assets/look.js (studio/looks/${look}). -->`);
  writeFileSync(ip, idx);
  const mp = join(dst, "meta.json");
  const meta = JSON.parse(readFileSync(mp, "utf8")); meta.id = meta.name = `${slug}-${look}`; writeFileSync(mp, JSON.stringify(meta, null, 2) + "\n");
  const sp = join(dst, "STORYBOARD.md");
  if (existsSync(sp)) writeFileSync(sp, `# ${slug} · ${look} look\n\nSame script, voice, timing and scenes as \`../${slug}-apple\` (see its STORYBOARD.md), restyled by the \`${look}\` look (\`studio/looks/${look}\`, copied to \`assets/look.css\` / \`assets/look.js\`). Generated by \`node studio/tools/make-looks.mjs ${slug}\`; edit the apple build and rerun, don't edit this copy.\n`);
  console.log(`made ${basename(dst)}`);
}
